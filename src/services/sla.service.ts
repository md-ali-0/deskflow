/**
 * ============================================================================
 *                    DESKFLOW - SLA SERVICE (সার্ভিস লেভেল এগ্রিমেন্ট)
 * ============================================================================
 * 
 * [আর্কিটেকচারাল গুরুত্ব / Architecture & Interview Value]:
 * SLA (Service Level Agreement) যেকোনো এন্টারপ্রাইজ হেল্পডেস্কের মেরুদণ্ড।
 * কোন টিকিট কখন সমাধান করতে হবে তা এই সার্ভিসের মাধ্যমে নিখুঁতভাবে নির্ধারিত হয়।
 * 
 * [ডিজাইন প্রিন্সিপালস / Design Principles]:
 * ১. Pure Function: এই ফাংশনটির কোনো সাইড ইফেক্ট (Side-effect) নেই।
 *    একই ইনপুট দিলে সবসময় একই আউটপুট পাওয়া যায়।
 * ২. Immutability (অপরিবর্তনীয়তা): 
 *    ইনপুট হিসেবে আসা `createdAt` অবজেক্টকে সরাসরি মিউটেট না করে `new Date(createdAt)`
 *    ক্লোন করা হয়েছে। জাভাস্ক্রিপ্টে ডেট অবজেক্ট রেফারেন্স ভিত্তিক কাজ করে, তাই ক্লোন 
 *    না করলে কলারের মূল ডেট নষ্ট হয়ে যাওয়ার ঝুঁকি থাকে।
 * ৩. Server Clock Authority: 
 *    ক্লায়েন্টের ডিভাইসের সময় বা টাইমজোনের ওপর নির্ভর না করে সার্ভারের বিশ্বস্ত 
 *    টাইমস্ট্যাম্পে ডেডলাইন হিসাব করা হয়, যা সিকিউরিটির জন্য অত্যন্ত জরুরি।
 * ৪. Unit Testability: কোনো ডাটাবেজ মক ছাড়াই মিলি-সেকেন্ডে টেস্ট করা সম্ভব।
 * ============================================================================
 */

/**
 * টিকিটের তৈরির সময় এবং ক্যাটাগরির SLA ঘন্টার ওপর ভিত্তি করে ডেডলাইন বের করে।
 * 
 * @param createdAt টিকিট তৈরির শুরুর তারিখ/সময় (UTC)
 * @param slaHours ক্যাটাগরিতে নির্ধারিত সমাধানের অনুমোদিত সর্বোচ্চ সময় (ঘন্টায়)
 * @returns Date অবজেক্ট যা নির্দেশ করে টিকিটটির সর্বশেষ সমাধানের সময়সীমা (dueAt)
 */
export function calculateDueAt(createdAt: Date, slaHours: number): Date {
  // মূল ডেট অপরিবর্তিত রাখতে নতুন ডেট কপি তৈরি করা হলো
  const d = new Date(createdAt);
  // বর্তমান ঘন্টার সাথে অনুমোদিত SLA ঘন্টা যোগ করা হচ্ছে
  d.setHours(d.getHours() + slaHours);
  return d;
}
