/**
 * ============================================================================
 *                    DESKFLOW - FINITE STATE MACHINE (FSM RULES)
 * ============================================================================
 * 
 * [আর্কিটেকচারাল গুরুত্ব / State Machine Architecture]:
 * সাধারণ ক্রুড (CRUD) অ্যাপ্লিকেশনে যেকোনো ফিল্ড যেমন খুশি আপডেট করা যায়। কিন্তু 
 * এন্টারপ্রাইজ হেল্পডেস্কে টিকিটের একটি কঠোর জীবনচক্র (Lifecycle) বজায় রাখা আবশ্যক।
 * এই ফাইলটি টিকিটের "Deterministic State Transition Graph" পরিচালনা করে।
 * 
 * [ইন্টারভিউ স্পেশাল পয়েন্ট / Key Talking Points for Interview]:
 * ১. Finite State Machine (FSM):
 *    - টিকিটের স্ট্যাটাস যেকোনো স্থান থেকে যেকোনো স্থানে জাম্প করতে পারে না।
 *    - যেমন: সরাসরি OPEN থেকে RESOLVED হওয়া নিষিদ্ধ (মাঝে কাজ বা তদন্তের প্রমাণ থাকতে হবে)।
 * ২. Terminal State (চূড়ান্ত অবস্থা):
 *    - 'CLOSED' হলো একটি টার্মিনাল স্টেট (`CLOSED: []`)। একবার কোনো টিকিট ক্লোজড হলে 
 *      সেখান থেকে আর কোনো স্ট্যাটাসে যাওয়া যায় না (Immutability of Closed Tickets)।
 * ৩. Server-Side Enforcement:
 *    - এই রুলসগুলো ক্লায়েন্টের জাভাস্ক্রিপ্ট কোডের ওপর নির্ভর করে না; সরাসরি সার্ভারে ভ্যালিডেট হয়।
 *    - তাই কেউ সরাসরি API বা curl দিয়ে ম্যানিপুলেট করতে চাইলে সার্ভার ৪২২ আনপ্রসেসএবল রিটার্ন করবে।
 * ৪. Business QA Guard (canResolve):
 *    - গ্রাহককে সমাধান না জানিয়ে এজেন্ট যাতে অলসতাবশত টিকিট 'RESOLVED' না করে, 
 *      সেজন্য অন্তত ১টি পাবলিক রিপ্লাই (publicReplyCount > 0) বাধ্যতামূলক করা হয়েছে।
 * ============================================================================
 */

/**
 * অনুমোদিত স্ট্যাটাস পরিবর্তনের ট্রানজিশন টেবিল (Directed Graph)।
 * কী (Key) নির্দেশ করে বর্তমান স্ট্যাটাস এবং ভ্যালু (Array) নির্দেশ করে পরবর্তী গ্রহণযোগ্য স্ট্যাটাসসমূহ।
 */
export const ALLOWED_TRANSITIONS: Record<string, string[]> = {
  // OPEN টিকিট নিয়ে কাজ শুরু হতে পারে (IN_PROGRESS) অথবা স্প্যাম হলে সরাসরি বাতিল (CLOSED)
  OPEN: ["IN_PROGRESS", "CLOSED"],

  // কাজের অগ্রগতি শেষে সমাধানে যাবে (RESOLVED) অথবা এজেন্ট রিলিজ করলে কিউতে ফেরত আসবে (OPEN)
  IN_PROGRESS: ["RESOLVED", "OPEN"],

  // সমাধান কাস্টমার নিশ্চিত করলে ক্লোজ হবে (CLOSED) অথবা কাস্টমারের সমস্যা থেকে গেলে পুনরায় কাজ শুরু (IN_PROGRESS)
  RESOLVED: ["CLOSED", "IN_PROGRESS"],

  // CLOSED টিকিট টার্মিনাল স্টেট - এখান থেকে আর কোনো ট্রানজিশন অনুমোদিত নয়
  CLOSED: [],
};

/**
 * বর্তমান স্ট্যাটাস থেকে পরবর্তী প্রস্তাবিত স্ট্যাটাসে রূপান্তর বৈধ কি না তা যাচাই করে।
 * 
 * @param from টিকিটের বর্তমান ডাটাবেজ স্ট্যাটাস
 * @param to ইউজার যে স্ট্যাটাসে রূপান্তর করতে চাচ্ছে
 * @returns boolean (অনুমোদিত হলে true, অবৈধ রূপান্তর হলে false)
 */
export function isTransitionAllowed(from: string, to: string): boolean {
  return (ALLOWED_TRANSITIONS[from] ?? []).includes(to);
}

/**
 * কোয়ালিটি কন্ট্রোল গার্ড: টিকিটে কোনো পাবলিক রিপ্লাই ছাড়া রেজোলিউশন অনুমোদন করে না।
 * 
 * @param publicReplyCount টিকিটের পাবলিক কমেন্ট সংখ্যা (Internal Note বাদ দিয়ে)
 * @returns boolean (১ বা তার বেশি পাবলিক রিপ্লাই থাকলে true)
 */
export function canResolve(publicReplyCount: number): boolean {
  return publicReplyCount > 0;
}
